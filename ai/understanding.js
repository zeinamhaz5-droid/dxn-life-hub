// 19. النية الرئيسية
// ======================================================

function detectIntent(text = "") {
  if (isIdentityQuestion(text)) {
    return "identity";
  }


  if (isCapabilityQuestion(text)) {
    return "capabilities";
  }


  const role = detectUserRole(text);


  // الهوية الصريحة لها الأولوية
  if (role === "customer") {
    return "customer";
  }


  if (role === "trainee") {
    return "trainee";
  }


  if (role === "leader") {
    return "leader";
  }


  // التدريب
  if (isTrainingRequest(text)) {
    return "training";
  }


  // التدريب العملي
  if (isPracticalRequest(text)) {
    return "practical_training";
  }


  // المنتجات
  if (isProductRecommendationRequest(text)) {
    return "product_recommendation";
  }


  if (isProductRequest(text)) {
    return "product";
  }


  // الرسائل الجاهزة
  if (isReadyMessageRequest(text)) {
    return "ready_message";
  }


  // التصحيح
  if (isCorrectionRequest(text)) {
    return "correction";
  }


  // DXN العام
  if (isDXNGeneralQuestion(text)) {
    return "dxn_general";
  }


  return "general";
}


// ======================================================
// 20. بناء فهم كامل للرسالة
// ======================================================

function understandMessage(text = "") {
  const originalText = String(text);

  const normalizedText =
    normalizeArabic(originalText);

  const role =
    detectUserRole(originalText);

  const intent =
    detectIntent(originalText);

  const topic =
    detectTopic(originalText);

  const experienceLevel =
    detectExperienceLevel(originalText);

  return {
    originalText,

    normalizedText,

    compactText:
      compactText(originalText),

    intent,

    role,

    topic,

    experienceLevel,

    product: {
      requested:
        isProductRequest(originalText),

      recommendation:
        isProductRecommendationRequest(originalText)
    },

    training: {
      requested:
        isTrainingRequest(originalText),

      type:
        detectTrainingType(originalText),

      practical:
        isPracticalRequest(originalText),

      correction:
        isCorrectionRequest(originalText)
    },

    readyMessage:
      isReadyMessageRequest(originalText),

    shortContextQuestion:
      isShortContextQuestion(originalText),

    wordCount:
      wordCount(originalText)
  };
}


