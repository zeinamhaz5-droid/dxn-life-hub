function detectUserRole(text = "") {
  const q = normalizeArabic(text);


  // ------------------------------------------------------
  // أولوية قصوى:
  // نفي أن المستخدم زبون
  // ------------------------------------------------------

  if (
    containsAny(q, [
      "انا مش زبون",
      "انا مش عميل",
      "انا لست زبون",
      "انا لست عميل",
      "ماني زبون",
      "ماني عميل",
      "مو زبون",
      "مو عميل",
      "مش زبون",
      "مش عميل"
    ])
  ) {
    return "trainee";
  }


  // ------------------------------------------------------
  // أولوية قصوى:
  // هوية المتدرب الصريحة
  // ------------------------------------------------------

  if (
    containsAny(q, [
      "انا متدرب",
      "انا متدربه",
      "انا متدرب جديد",
      "انا متدربه جديده",
      "انا عضو جديد",
      "انا عضوه جديده",
      "بدي اتدرب",
      "بدي اتعلم",
      "بدي تعلم",
      "بدي طور حالي",
      "بدي اتطور",
      "دربني",
      "اختبرني",
      "قيم مستواي",
      "اختبر خبرتي",
      "بدي اعرف مستواي"
    ])
  ) {
    return "trainee";
  }


  // ------------------------------------------------------
  // أولوية قصوى:
  // هوية الزبون الصريحة
  // ------------------------------------------------------

  if (
    containsAny(q, [
      "انا زبون",
      "انا زبونه",
      "انا عميل",
      "انا عميله",
      "انا زبون جديد",
      "انا زبونه جديده",
      "انا عميل جديد",
      "انا عميله جديده"
    ])
  ) {
    return "customer";
  }


  // ------------------------------------------------------
  // هوية القائد
  // ------------------------------------------------------

  if (
    containsAny(q, [
      "انا قائد",
      "انا ليدر",
      "انا leader",
      "عندي فريق",
      "عندي تيم",
      "عندي مجموعه",
      "بني فريق",
      "عم ببني فريق",
      "مسؤول عن فريق",
      "عندي اعضاء"
    ])
  ) {
    return "leader";
  }


  // ------------------------------------------------------
  // طلبات واضحة للتدريب
  // ------------------------------------------------------

  const trainingSignals = [
    "دربني",
    "بدي تدريب",
    "بدي اتدرب",
    "اختبرني",
    "اعمللي اختبار",
    "اعمل لي اختبار",
    "خلينا نتدرب",
    "خلينا نتمرن",
    "علمني",
    "بدي اتعلم",
    "بدي تعلم",
    "كيف اتطور",
    "بدي طور حالي",
    "قيم مستواي",
    "قيمني",
    "شوف مستواي",
    "اختبر خبرتي",
    "شوف خبرتي",
    "تمرني",
    "تمرن معي"
  ];

  if (containsAny(q, trainingSignals)) {
    return "trainee";
  }


  // ------------------------------------------------------
  // سيناريوهات تدريبية مع زبون
  // مهم:
  // كلمة "زبون" لا تعني أن المستخدم زبون.
  // ------------------------------------------------------

  const trainingScenarioSignals = [
    "كيف اتعامل مع زبون",
    "كيف اتعامل مع عميل",
    "كيف اقنع الزبون",
    "كيف اقنع العميل",
    "الزبون قال",
    "العميل قال",
    "اذا الزبون",
    "اذا العميل",
    "اعتراض الزبون",
    "اعتراض العميل",
    "موقف مع زبون",
    "موقف مع عميل",
    "زبون غالي",
    "عميل غالي",
    "الزبون رفض",
    "العميل رفض",
    "الزبون ما بدو",
    "العميل ما بدو",
    "الزبون ما اقتنع",
    "العميل ما اقتنع"
  ];

  if (containsAny(q, trainingScenarioSignals)) {
    return "trainee";
  }


  // ------------------------------------------------------
  // لا نحدد زبون تلقائيًا من كلمة "منتج" وحدها.
  //
  // السبب:
  // إذا كان المستخدم قال سابقًا "أنا متدرب"
  // ثم قال "شو سعر القهوة؟"
  // يجب ألا نغير دوره إلى زبون.
  //
  // سيتم استخدام هذه الإشارات لتحديد النية،
  // وليس فرض الدور إذا لم يصرح المستخدم بدوره.
  // ------------------------------------------------------

  return null;
}


