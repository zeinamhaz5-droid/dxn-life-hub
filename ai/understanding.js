function detectTrainingType(text = "") {
  const q = normalizeArabic(text);

  if (
    containsAny(q, [
      "اختبرني",
      "اختبار",
      "قيم مستواي",
      "قيمني",
      "شوف مستواي",
      "اختبر خبرتي"
    ])
  ) {
    return "assessment";
  }


  if (
    containsAny(q, [
      "علمني",
      "شرحلي",
      "فهمني",
      "بدي اتعلم",
      "بدي تعلم"
    ])
  ) {
    return "learning";
  }


  if (
    containsAny(q, [
      "موقف",
      "سيناريو",
      "عميل",
      "زبون",
      "اعتراض",
      "قال السعر غالي",
      "السعر غالي",
      "غالي شوي",
      "غالي"
    ])
  ) {
    return "scenario";
  }


  if (
    containsAny(q, [
      "بيع",
      "ابيع",
      "مبيعات",
      "كيف ابيع",
      "كيف بيع"
    ])
  ) {
    return "sales";
  }


  if (
    containsAny(q, [
      "متابعه",
      "تابع",
      "follow up",
      "فولو"
    ])
  ) {
    return "follow_up";
  }


  if (
    containsAny(q, [
      "فريق",
      "بناء الفريق",
      "اعضاء",
      "قياده",
      "قائد",
      "ليدر"
    ])
  ) {
    return "team_building";
  }


  return "general_training";
}


