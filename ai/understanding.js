// ======================================================
// 7. سؤال DXN العام
// ======================================================

function isDXNGeneralQuestion(text = "") {
  const q = normalizeArabic(text);

  const hasDXN =
    q.includes("dxn") ||
    q.includes("دكسن") ||
    q.includes("دي اكس ان") ||
    q.includes("دي اكسن") ||
    q.includes("ديكسن");

  if (!hasDXN) {
    return false;
  }

  return (
    containsAny(q, [
      "شو هي",
      "ما هي",
      "شو هية",
      "شو بتعمل",
      "شو هي الشركه",
      "خبرني عن",
      "احكيلي عن",
      "شرحلي",
      "شو قصتها",
      "شو نظامها",
      "كيف بتشتغل",
      "كيف العمل فيها"
    ]) ||
    q === "dxn" ||
    q === "دكسن" ||
    q === "دي اكس ان"
  );
}


